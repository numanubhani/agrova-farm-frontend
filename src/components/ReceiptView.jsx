import { useEffect, useState } from 'react';
import { Bills } from '../lib/api';
import { lt, monthName, rs, todayStr } from '../lib/format';
import { useAppState } from '../context/AppStateContext';

function formatDate(d) {
  return new Date(d + 'T00:00').toLocaleDateString('en-US', { day: 'numeric', month: 'short', year: 'numeric' });
}

export default function ReceiptView({ customer, onClose }) {
  const { month, farmName } = useAppState();
  const [data, setData] = useState(null);

  useEffect(() => { Bills.receipt(customer.id, month).then(setData); }, [customer.id, month]);

  if (!data) return <p className="hint">Loading…</p>;
  const { bill } = data;
  const no = 'INV-' + month.replace('-', '') + '-' + String(customer.id).padStart(3, '0');
  const rate = Number(customer.rate);
  const msg =
    `${farmName}\nInvoice ${no} · ${monthName(month)}\n${customer.name}\n` +
    `Milk: ${lt(bill.liters)} x Rs ${rate} = ${rs(bill.amount)}\n` +
    `Previous balance: ${rs(bill.prev)}\nPaid: ${rs(bill.paid)}\nTotal due: ${rs(bill.balance)}`;
  const ph = (customer.phone || '').replace(/[^\d]/g, '').replace(/^0/, '92');
  const daysDelivered = data.days.filter((d) => Number(d.liters) > 0);

  return (
    <>
      <div id="receipt" className="invoice">
        <div className="inv-head">
          <div className="inv-brand">
            <div className="inv-logo">🐄</div>
            <div>
              <h4>{farmName}</h4>
              <div className="inv-sub">Dairy Milk Supply</div>
            </div>
          </div>
          <div className="inv-meta">
            <div className="inv-tag">INVOICE</div>
            <div className="inv-no">{no}</div>
            <div className="inv-sub">Issued {formatDate(todayStr())}</div>
          </div>
        </div>

        <div className="inv-parties">
          <div>
            <small>Bill To</small>
            <b>{customer.name}</b>
            {customer.phone && <div className="inv-sub">{customer.phone}</div>}
          </div>
          <div className="inv-right">
            <small>Billing Period</small>
            <b>{monthName(month)}</b>
          </div>
        </div>

        <table className="inv-table">
          <thead>
            <tr><th>Description</th><th>Amount</th></tr>
          </thead>
          <tbody>
            <tr>
              <td>
                Milk delivered
                <span className="inv-sub" style={{ display: 'block' }}>{monthName(month)} · {lt(bill.liters)} × Rs {rate}/L</span>
              </td>
              <td>{rs(bill.amount)}</td>
            </tr>
          </tbody>
        </table>

        <div className="inv-totals">
          <div className="kv"><span>This month's bill</span><b>{rs(bill.amount)}</b></div>
          <div className="kv"><span>Previous balance</span><b>{rs(bill.prev)}</b></div>
          <div className="kv"><span>Paid</span><b>−{rs(bill.paid)}</b></div>
          <div className="kv tot"><span>Total due</span><b style={{ color: bill.balance > 0 ? 'var(--red)' : 'var(--green)' }}>{rs(bill.balance)}</b></div>
        </div>

        {daysDelivered.length > 0 && (
          <div className="inv-days-block">
            <small>Daily Delivery Log</small>
            <div className="days">
              {daysDelivered.map((d) => (
                <span key={d.date}>{+d.date.slice(8)}<b>{d.liters}L</b></span>
              ))}
            </div>
          </div>
        )}

        <div className="inv-foot">
          Thank you for your business.
          <span className="inv-sub"> Generated by {farmName} · Agrova Farm Manager</span>
        </div>
      </div>
      <div className="acts">
        <button className="btn ghost" onClick={() => window.print()}>Print / PDF</button>
        <a className="btn" target="_blank" rel="noopener" href={`https://wa.me/${ph}?text=${encodeURIComponent(msg)}`}>WhatsApp</a>
      </div>
      <div className="acts" style={{ marginTop: 8 }}>
        <button className="btn ghost" onClick={onClose}>Close</button>
      </div>
    </>
  );
}
